#!/usr/bin/env python3
"""Render the production token stylesheet from the editable design system."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def stylesheet():
    tokens = json.loads((ROOT / 'tools/design-system/tokens.json').read_text())
    themes = tokens['color']['themes']
    names = set()
    values = {theme['id']: [] for theme in themes}
    for family in ('color', 'spacing', 'radius', 'shadow'):
        for token in tokens[family]['tokens']:
            name = token['name']
            if name in names or not token.get('usage'):
                raise ValueError('Duplicate or undocumented token: ' + name)
            names.add(name)
            for theme in themes:
                value = token['value']
                if isinstance(value, dict):
                    value = value[theme['id']]
                values[theme['id']].append(f'  --{name}: {value};')
    for name, family in tokens['type']['families'].items():
        for theme in themes:
            values[theme['id']].append(f'  --font-{name}: {family};')
    for group in tokens['type']['groups']:
        for style in group['styles']:
            for attribute, suffix in (('fontSize', 'size'), ('lineHeight', 'leading'), ('fontWeight', 'weight')):
                for theme in themes:
                    values[theme['id']].append(f'  --font-{style["name"]}-{suffix}: {style[attribute]};')
    light, dark = (theme['id'] for theme in themes)
    return (
        '/* Dig It website foundations; generated by tools/build_site_design.py. */\n'
        ':root {\n  color-scheme: light dark;\n' + '\n'.join(values[light]) + '\n}\n'
        '@media (prefers-color-scheme: dark) {\n  :root {\n'
        + '\n'.join('  ' + value for value in values[dark]) + '\n  }\n}\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'style/tokens.css'
    expected = stylesheet()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit('Outdated style/tokens.css; run tools/build_site_design.py')
        print('Design tokens are current.')
    else:
        target.write_text(expected)
        print('Generated style/tokens.css from the Dig It design system.')


if __name__ == '__main__':
    main()
